import { calcularFgas, proximoPreventivo, MAQUINA_VACIA } from '../src/lib/maquinaFgas.js';
let f = 0; const ok = (c, t, d = '') => { if (!c) { f++; console.log('  ✗ ' + t + (d ? ' — ' + d : '')); } else console.log('  ✓ ' + t); };
let r = calcularFgas({ refrigerant_type: 'R-410A', refrigerant_charge_kg: '2,5' });
ok(r.gwp === 2088 && r.tCO2 === 5.22, 'R-410A 2,5 kg = 5,22 t CO₂e', String(r.tCO2));
ok(r.control.estado === 'si' && r.control.meses === 12, '5–50 t: control cada 12 meses', r.control.texto);
r = calcularFgas({ refrigerant_type: 'R-410A', refrigerant_charge_kg: 2.5, leak_detection: true });
ok(r.control.meses === 24, 'con detector de fugas se duplica el plazo');
r = calcularFgas({ refrigerant_type: 'R-410A', refrigerant_charge_kg: 2.5, hermetic: true });
ok(r.control.estado === 'no' && /hermético/.test(r.control.texto), 'hermético < 10 t: no obligatorio');
r = calcularFgas({ refrigerant_type: 'R-32', refrigerant_charge_kg: 1.2 });
ok(r.tCO2 < 5 && r.control.estado === 'no', 'R-32 1,2 kg: < 5 t, no obligatorio', String(r.tCO2));
r = calcularFgas({ refrigerant_type: 'R-404A', refrigerant_charge_kg: 20 });
ok(r.tCO2 > 50 && r.control.meses === 6, 'R-404A 20 kg (78 t): cada 6 meses', `${r.tCO2} t, ${r.control.meses}`);
r = calcularFgas({ refrigerant_type: 'R-404A', refrigerant_charge_kg: 140 });
ok(r.control.meses === 3, '>500 t: cada 3 meses', `${r.tCO2}`);
r = calcularFgas({ refrigerant_type: 'R-1234yf', refrigerant_charge_kg: 10 });
ok(r.kgHFO === 10, 'HFO puro: toda la carga es HFO');
r = calcularFgas({ refrigerant_type: 'R-454B', refrigerant_charge_kg: 10 });
ok(Math.abs(r.kgHFO - 3.11) < 0.001, 'R-454B: 31,1 % HFO', String(r.kgHFO));
r = calcularFgas({ refrigerant_type: 'R-410A', refrigerant_charge_kg: 5 });
ok(r.kgHFO === 0, 'HFC sin HFO: 0 kg');
r = calcularFgas({ refrigerant_type: '' }); ok(r.tCO2 === null && r.control.estado === 'sin-datos', 'sin gas ni carga: faltan datos');
r = calcularFgas({ refrigerant_type: 'R-410A', refrigerant_charge_kg: 5, gwp: '1000' });
ok(r.tCO2 === 5 && r.gwp === 1000, 'PCA editable manda sobre el del gas');
r = calcularFgas({ refrigerant_type: 'R-410A', refrigerant_charge_kg: 5, last_leak_check: '2026-01-15' });
ok(r.control.proximo === '2027-01-15', 'próximo control = último + plazo', r.control.proximo);
ok(proximoPreventivo('2026-10-31', 6) === '2027-04-30' || proximoPreventivo('2026-10-31', 6) === '2027-05-01', 'próximo preventivo +6 meses', proximoPreventivo('2026-10-31', 6));
ok(proximoPreventivo('', 6) === null && proximoPreventivo('2026-01-01', '') === null, 'sin datos no inventa fechas');
ok(MAQUINA_VACIA.maintenance_interval_months === 6, 'ficha vacía: preventivo cada 6 meses');
console.log(f ? `\n${f} FALLOS` : '\nTODO OK'); process.exit(f ? 1 : 0);
