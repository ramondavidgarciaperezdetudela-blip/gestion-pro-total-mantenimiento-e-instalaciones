import { resumenAveria, diasEntre, costePiezas } from '../src/lib/averiasEstado.js';
let f = 0; const ok = (c, t) => { if (!c) { f++; console.log('  ✗ ' + t); } else console.log('  ✓ ' + t); };
const H = '2026-11-01';
ok(diasEntre('2026-10-25', H) === 7, 'días entre fechas');
ok(diasEntre('x', H) === null, 'fecha inválida → null');
let r = resumenAveria({ status: 'reparada', failure_date: '2026-10-20', repair_date: '2026-10-22' }, H);
ok(r.estado === 'ok' && r.dias === 2 && !r.abierta, 'reparada → verde, tardó 2 días');
r = resumenAveria({ status: 'en_reparacion', failure_date: '2026-10-30' }, H);
ok(r.estado === 'aviso' && r.dias === 2 && !r.urgente, 'en reparación reciente → ámbar');
r = resumenAveria({ status: 'en_reparacion', failure_date: '2026-10-01' }, H);
ok(r.estado === 'critico' && r.urgente, 'abierta >7 días → crítico');
r = resumenAveria({ status: 'pendiente', failure_date: '2026-10-31', failure_type: 'fugas_gas' }, H);
ok(r.estado === 'critico' && r.tipo === 'Fuga de gas', 'fuga de gas abierta → crítico');
r = resumenAveria({ status: 'reportada', failure_date: '2026-11-01' }, H);
ok(r.estado === 'critico', 'reportada → rojo');
r = resumenAveria({ status: 'cancelada' }, H); ok(r.estado === 'neutro', 'cancelada → gris');
ok(resumenAveria({}, H).estado === 'neutro', 'vacía no rompe');
ok(costePiezas({ parts_used: [{ cost: 10, quantity: 2 }, { cost: '5' }] }) === 25, 'coste piezas');
console.log(f ? `\n${f} FALLOS` : '\nTODO OK'); process.exit(f ? 1 : 0);
