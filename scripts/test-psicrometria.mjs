import { presionAltitud, presionSaturacion, estadoAire, cargaLatente } from '../src/lib/psicrometria.js';
let f = 0; const ok = (c, t, d = '') => { if (!c) { f++; console.log('  ✗ ' + t + (d ? ' — ' + d : '')); } else console.log('  ✓ ' + t); };
const cerca = (a, b, tol) => Math.abs(a - b) <= tol;
ok(cerca(presionAltitud(0), 101325, 1) && cerca(presionAltitud(1000), 89875, 150), 'presión a 0 y 1000 m');
ok(cerca(presionSaturacion(20), 2339, 15) && cerca(presionSaturacion(35), 5628, 40), 'Psat 20 °C ≈ 2339 Pa y 35 °C ≈ 5628 Pa');
const a = estadoAire({ t: 24, hr: 50, altitud: 0 });
ok(cerca(a.W, 0.0093, 0.0004), 'W a 24 °C / 50 %', a.W.toFixed(4));
ok(cerca(a.rho, 1.18, 0.02), 'densidad ≈ 1,18 kg/m³', a.rho.toFixed(3));
ok(cerca(a.tRocio, 12.9, 0.5), 'punto de rocío ≈ 12,9 °C', a.tRocio.toFixed(1));
ok(cerca(a.h, 47.6, 1), 'entalpía ≈ 47,6 kJ/kg', a.h.toFixed(1));
const alt = estadoAire({ t: 24, hr: 50, altitud: 1500 });
ok(alt.rho < a.rho * 0.88 && alt.rho > a.rho * 0.8, 'a 1500 m el aire es ~16 % menos denso', (alt.rho / a.rho).toFixed(3));
ok(estadoAire({ t: 20, hr: 120 }) === null && estadoAire({ t: 'x', hr: 50 }) === null, 'entradas inválidas → null');
ok(estadoAire({ t: '24,5', hr: '50' }) !== null, 'acepta coma decimal');
const c = cargaLatente({ interior: { t: 24, hr: 50 }, exterior: { t: 35, hr: 40 }, altitud: 0, caudalM3h: 1000, personas: 10 });
ok(c.ventLatenteKW > 0 && c.ventSensibleKW > 0, 'ventilación de verano: latente y sensible positivos');
ok(cerca(c.personasLatenteKW, 0.55, 1e-9), '10 personas × 55 W = 0,55 kW');
ok(cerca(c.totalKW, c.latenteKW + c.sensibleKW, 1e-9) && c.fcs > 0 && c.fcs < 1, 'total = latente + sensible; FCS entre 0 y 1');
ok(cerca(c.ventSensibleKW, 3.5, 0.9), 'sensible vent. 1000 m³/h ΔT 11 K ≈ 3,5 kW', c.ventSensibleKW.toFixed(2));
const inv = cargaLatente({ interior: { t: 22, hr: 50 }, exterior: { t: 5, hr: 60 }, altitud: 0, caudalM3h: 500 });
ok(inv.ventLatenteKW < 0 && inv.latenteKW === 0, 'invierno: el aire exterior es más seco → no hay carga latente a retirar');
const fu = cargaLatente({ interior: { t: 24, hr: 50 }, exterior: { t: 24, hr: 50 }, altitud: 0, caudalM3h: 0, humedadKgH: 3.6 });
ok(cerca(fu.fuentesKW, 2.501, 0.01) && cerca(fu.deshumidificarKgH, 3.6, 0.01), '3,6 kg/h de agua = 2,5 kW latentes');
console.log(f ? `\n${f} FALLOS` : '\nTODO OK'); process.exit(f ? 1 : 0);
